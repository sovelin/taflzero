"""
Binary dataset reader for AlphaZero self-play data generated by Rust MCTS.

Sample binary format v2 (variable-length):
    BitPosition     50 bytes   (3×16 bytes planes + 1 byte stm + 1 byte rep)
    LegalMask       605 bytes  (4840 bits packed)
    policy_len      u16        (2 bytes)
    PolicyTarget×N  N×4 bytes  (move_index u16 + visits u16 each)
    value           i8         (1 byte, final game result z from stm perspective)
    root_q          i8         (1 byte, MCTS root Q × 127 from stm perspective)
    flags           u8         (bit0 policy_valid, bit1 last_of_game)
    king_corner     u8         (0-3 escape corner index in [0,10,110,120], 255 none)

The v1 format (T1 runs) lacks the trailing flags/king_corner bytes — pass
legacy=True to read those files.

Value target = z_lambda * z + (1 - z_lambda) * root_q  (bootstrapped, lower
variance).  For cheap-search samples (policy_valid=0, playout cap
randomization) root_q comes from a low-node search, so the target falls back
to pure z.

Network input planes (11 × 11 × 11):
    0: attackers       (from BitPosition planes[0..16])
    1: defenders       (from BitPosition planes[16..32])
    2: king            (from BitPosition planes[32..48])
    3: side-to-move    (all 1s if stm==1, else all 0s)
    4: throne          (square 60)
    5: corners         (squares 0, 10, 110, 120)
    6: edge squares    (all 40 edge squares)
    7: group BFS       (reachability of king+defenders through non-attacker squares)
    8: king BFS        (reachability of king through empty squares)
    9: repetition x1   (all 1s if rep >= 2)
    10: repetition x2  (all 1s if rep >= 3)
"""

from __future__ import annotations

import struct
from collections import deque
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset

BOARD_SIZE = 11
SQS = BOARD_SIZE * BOARD_SIZE  # 121
NUM_PLANES = 11
POLICY_SIZE = 4840

BIT_POSITION_BYTES = 50  # 48 planes + 1 stm + 1 rep
LEGAL_MASK_BYTES = 605   # ceil(4840 / 8)
FIXED_HEADER = BIT_POSITION_BYTES + LEGAL_MASK_BYTES + 2  # 657 bytes before policy entries

# Sample tail after the policy entries
TAIL_BYTES_V2 = 4  # value + root_q + flags + king_corner
TAIL_BYTES_V1 = 2  # value + root_q

FLAG_POLICY_VALID = 1 << 0
FLAG_LAST_OF_GAME = 1 << 1

KING_CORNER_NONE_RAW = 255
CORNER_CLASS_NONE = 4  # class index for "game did not end with a corner escape"

THRONE_SQ = 5 * 11 + 5   # 60
CORNERS_SQ = [0, 10, 110, 120]
EDGES_SQ = [sq for sq in range(SQS)
            if sq // BOARD_SIZE == 0 or sq // BOARD_SIZE == BOARD_SIZE - 1
            or sq % BOARD_SIZE == 0 or sq % BOARD_SIZE == BOARD_SIZE - 1]

# Orthogonal neighbors for BFS
_NEIGHBORS: list[list[int]] = []
for _sq in range(SQS):
    _r, _c = _sq // BOARD_SIZE, _sq % BOARD_SIZE
    _nb = []
    if _r > 0: _nb.append(_sq - BOARD_SIZE)
    if _r < BOARD_SIZE - 1: _nb.append(_sq + BOARD_SIZE)
    if _c > 0: _nb.append(_sq - 1)
    if _c < BOARD_SIZE - 1: _nb.append(_sq + 1)
    _NEIGHBORS.append(_nb)

# Precompute static planes once
_THRONE_PLANE = np.zeros(SQS, dtype=np.float32)
_THRONE_PLANE[THRONE_SQ] = 1.0

_CORNERS_PLANE = np.zeros(SQS, dtype=np.float32)
for _sq in CORNERS_SQ:
    _CORNERS_PLANE[_sq] = 1.0

_EDGES_PLANE = np.zeros(SQS, dtype=np.float32)
for _sq in EDGES_SQ:
    _EDGES_PLANE[_sq] = 1.0


def _bfs_reach(seeds: list[int], passable: np.ndarray) -> np.ndarray:
    """BFS flood-fill on 11x11 board. passable is bool array [SQS]."""
    visited = np.zeros(SQS, dtype=np.float32)
    queue: deque[int] = deque()
    for s in seeds:
        if passable[s] and not visited[s]:
            visited[s] = 1.0
            queue.append(s)
    while queue:
        sq = queue.popleft()
        for nb in _NEIGHBORS[sq]:
            if passable[nb] and not visited[nb]:
                visited[nb] = 1.0
                queue.append(nb)
    return visited

# ============================================================
# Board symmetry augmentation (D4: 4 rotations + 4 reflections)
# Directions: Up=0, Down=1, Left=2, Right=3
# ============================================================
_N = BOARD_SIZE - 1  # 10

_SYM_POS = [
    lambda r, c: (r, c),
    lambda r, c: (c, _N - r),
    lambda r, c: (_N - r, _N - c),
    lambda r, c: (_N - c, r),
    lambda r, c: (r, _N - c),
    lambda r, c: (_N - r, c),
    lambda r, c: (c, r),
    lambda r, c: (_N - c, _N - r),
]

_DIR_MAPS = [
    [0, 1, 2, 3],  # identity
    [3, 2, 0, 1],  # rot90CW:  Up->Right, Down->Left, Left->Up,    Right->Down
    [1, 0, 3, 2],  # rot180:   Up->Down,  Down->Up,   Left->Right, Right->Left
    [2, 3, 1, 0],  # rot270CW: Up->Left,  Down->Right, Left->Down, Right->Up
    [0, 1, 3, 2],  # flipH:    Up->Up,    Down->Down,  Left->Right, Right->Left
    [1, 0, 2, 3],  # flipV:    Up->Down,  Down->Up,    Left->Left,  Right->Right
    [2, 3, 0, 1],  # flipD:    Up->Left,  Down->Right, Left->Up,   Right->Down
    [3, 2, 1, 0],  # flipA:    Up->Right, Down->Left,  Left->Down, Right->Up
]


def _build_policy_perm(sym_idx: int) -> np.ndarray:
    """Precompute gather permutation: new_policy = old_policy[perm]."""
    pos_fn = _SYM_POS[sym_idx]
    dir_map = _DIR_MAPS[sym_idx]
    DIRS, MAX_DIST = 4, 10
    perm = np.empty(POLICY_SIZE, dtype=np.int32)
    for sq in range(SQS):
        r, c = sq // BOARD_SIZE, sq % BOARD_SIZE
        new_r, new_c = pos_fn(r, c)
        new_sq = new_r * BOARD_SIZE + new_c
        for d in range(DIRS):
            new_d = dir_map[d]
            for dist in range(MAX_DIST):
                old_idx = sq * (DIRS * MAX_DIST) + d * MAX_DIST + dist
                new_idx = new_sq * (DIRS * MAX_DIST) + new_d * MAX_DIST + dist
                perm[new_idx] = old_idx
    return perm


# Precomputed permutations as torch tensors (computed once at import)
_POLICY_PERMS = [torch.from_numpy(_build_policy_perm(i)).long() for i in range(8)]


def _build_corner_perm(sym_idx: int) -> list[int]:
    """corner class i (square CORNERS_SQ[i]) maps to this class after symmetry."""
    pos_fn = _SYM_POS[sym_idx]
    mapping = []
    for sq in CORNERS_SQ:
        r, c = sq // BOARD_SIZE, sq % BOARD_SIZE
        new_r, new_c = pos_fn(r, c)
        mapping.append(CORNERS_SQ.index(new_r * BOARD_SIZE + new_c))
    mapping.append(CORNER_CLASS_NONE)  # "none" is symmetry-invariant
    return mapping


_CORNER_PERMS = [_build_corner_perm(i) for i in range(8)]


def _apply_board_sym(planes: np.ndarray, sym_idx: int) -> np.ndarray:
    """Apply spatial symmetry to board planes (NUM_PLANES, 11, 11)."""
    if sym_idx == 1:
        return np.ascontiguousarray(np.rot90(planes, k=3, axes=(1, 2)))
    elif sym_idx == 2:
        return np.ascontiguousarray(np.rot90(planes, k=2, axes=(1, 2)))
    elif sym_idx == 3:
        return np.ascontiguousarray(np.rot90(planes, k=1, axes=(1, 2)))
    elif sym_idx == 4:
        return np.ascontiguousarray(np.flip(planes, axis=2))
    elif sym_idx == 5:
        return np.ascontiguousarray(np.flip(planes, axis=1))
    elif sym_idx == 6:
        return np.ascontiguousarray(np.swapaxes(planes, 1, 2))
    else:  # sym_idx == 7
        return np.ascontiguousarray(np.swapaxes(np.rot90(planes, k=2, axes=(1, 2)), 1, 2))


def _unpack_bits(data: bytes, num_bits: int) -> np.ndarray:
    """Unpack packed bytes into a float32 array of 0s and 1s."""
    raw = np.frombuffer(data, dtype=np.uint8)
    bits = np.unpackbits(raw, bitorder="little")[: num_bits]
    return bits.astype(np.float32)


def _build_offset_index(path: Path, tail_bytes: int = TAIL_BYTES_V2) -> np.ndarray:
    """Scan the binary file and return an array of byte offsets for each sample.

    Only reads the minimum needed (policy_len field) to compute sample sizes.
    """
    file_size = path.stat().st_size
    offsets: list[int] = []
    pos = 0
    with open(path, "rb") as f:
        while pos < file_size:
            offsets.append(pos)
            # Skip fixed header to reach policy_len
            f.seek(pos + BIT_POSITION_BYTES + LEGAL_MASK_BYTES)
            raw = f.read(2)
            if len(raw) < 2:
                break
            policy_len = struct.unpack("<H", raw)[0]
            # Advance past policy entries + tail
            pos += FIXED_HEADER + policy_len * 4 + tail_bytes
    return np.array(offsets, dtype=np.int64)


def _decode_policy(policy_raw: bytes, policy_len: int) -> np.ndarray:
    """Sparse policy entries → dense normalized distribution (or zeros)."""
    policy_visits = np.zeros(POLICY_SIZE, dtype=np.float32)
    for i in range(policy_len):
        off = i * 4
        move_index = struct.unpack_from("<H", policy_raw, off)[0]
        visits = struct.unpack_from("<H", policy_raw, off + 2)[0]
        policy_visits[move_index] = float(visits)
    visit_sum = policy_visits.sum()
    if visit_sum > 0:
        policy_visits /= visit_sum
    return policy_visits


def _read_aux_policy_at(f, offset: int) -> tuple[np.ndarray, np.ndarray, bool]:
    """Light v2 read of a sample's policy + legal mask (for the opponent-reply
    auxiliary target).  Skips plane/BFS decoding entirely."""
    f.seek(offset + 48 + 2)  # skip planes + stm + rep
    legal_mask_bytes = f.read(LEGAL_MASK_BYTES)
    policy_len = struct.unpack("<H", f.read(2))[0]
    policy_raw = f.read(policy_len * 4)
    f.seek(2, 1)  # skip value + root_q
    flags = f.read(1)[0]

    policy = _decode_policy(policy_raw, policy_len)
    legal_mask = _unpack_bits(legal_mask_bytes, POLICY_SIZE)
    valid = bool(flags & FLAG_POLICY_VALID) and policy.sum() > 0
    return policy, legal_mask, valid


def _read_sample_at(
    f, offset: int, z_lambda: float = 0.5, legacy: bool = False,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, bool, bool, int, int]:
    """Read and decode a single sample from an open file handle at the given offset.

    Returns (planes, legal_mask, policy, value_target,
             policy_valid, last_of_game, corner_class, next_offset).
    """
    f.seek(offset)

    # BitPosition: 50 bytes (48 planes + 1 stm + 1 rep)
    planes_bytes = f.read(48)
    stm = f.read(1)[0]
    rep = f.read(1)[0]

    # LegalMask: 605 bytes
    legal_mask_bytes = f.read(LEGAL_MASK_BYTES)

    # policy_len: u16
    policy_len = struct.unpack("<H", f.read(2))[0]

    # PolicyTarget × N: each 4 bytes (move_index u16, visits u16)
    policy_raw = f.read(policy_len * 4)

    # value: i8 (final result z), root_q: i8 (MCTS root Q × 127)
    value = struct.unpack("<b", f.read(1))[0]
    root_q = struct.unpack("<b", f.read(1))[0] / 127.0

    if legacy:
        policy_valid = True
        last_of_game = True  # unknown in v1 — disables the aux opponent target
        corner_class = CORNER_CLASS_NONE
        next_offset = offset + FIXED_HEADER + policy_len * 4 + TAIL_BYTES_V1
    else:
        flags = f.read(1)[0]
        corner_raw = f.read(1)[0]
        policy_valid = bool(flags & FLAG_POLICY_VALID)
        last_of_game = bool(flags & FLAG_LAST_OF_GAME)
        corner_class = CORNER_CLASS_NONE if corner_raw == KING_CORNER_NONE_RAW else int(corner_raw)
        next_offset = offset + FIXED_HEADER + policy_len * 4 + TAIL_BYTES_V2

    # -- Decode piece planes --
    attackers = _unpack_bits(planes_bytes[0:16], SQS)
    defenders = _unpack_bits(planes_bytes[16:32], SQS)
    king = _unpack_bits(planes_bytes[32:48], SQS)
    stm_plane = np.full(SQS, float(stm), dtype=np.float32)

    # -- BFS planes --
    atk_mask = attackers.astype(bool)
    def_mask = defenders.astype(bool)
    king_mask = king.astype(bool)

    # Group BFS: seeds = king + defenders, passable = non-attacker
    group_seeds = list(np.where(king_mask | def_mask)[0])
    passable_group = ~atk_mask
    group_bfs = _bfs_reach(group_seeds, passable_group)

    # King BFS: seeds = king, passable = king's own square or empty (not atk, not def)
    king_seeds = list(np.where(king_mask)[0])
    passable_king = ~atk_mask & ~def_mask
    king_bfs = _bfs_reach(king_seeds, passable_king)

    # -- Repetition planes --
    rep1_plane = np.full(SQS, 1.0 if rep >= 2 else 0.0, dtype=np.float32)
    rep2_plane = np.full(SQS, 1.0 if rep >= 3 else 0.0, dtype=np.float32)

    board_planes = np.stack([
        attackers, defenders, king, stm_plane,
        _THRONE_PLANE, _CORNERS_PLANE, _EDGES_PLANE,
        group_bfs, king_bfs,
        rep1_plane, rep2_plane,
    ]).reshape(NUM_PLANES, BOARD_SIZE, BOARD_SIZE)

    # -- Legal mask --
    legal_mask = _unpack_bits(legal_mask_bytes, POLICY_SIZE)

    # -- Policy target: sparse → dense, then normalize --
    policy_visits = _decode_policy(policy_raw, policy_len)

    # Bootstrapped value target: mix final result with search estimate.
    # Cheap-search samples (PCR) have a low-node root_q — use pure z for them.
    if policy_valid:
        value_target = z_lambda * float(value) + (1.0 - z_lambda) * root_q
    else:
        value_target = float(value)

    return (
        torch.from_numpy(board_planes),
        torch.from_numpy(legal_mask).bool(),
        torch.from_numpy(policy_visits),
        torch.tensor(np.float32(value_target)),
        policy_valid,
        last_of_game,
        corner_class,
        next_offset,
        root_q,  # search's assessment of THIS position (decidedness signal)
    )


class SelfPlayDataset(Dataset):
    """
    PyTorch dataset that reads self-play samples lazily from disk.

    Only an index of byte offsets is kept in memory.  Each __getitem__
    call reads and decodes a single sample from the file, so RAM usage
    stays constant regardless of dataset size.

    Compatible with DataLoader(num_workers>0): each worker opens its
    own file handle on first access (stored as an instance attribute
    that lives in the worker process).

    Args:
        path: path to binary data file
        window_size: if > 0, only use the last `window_size` samples
        z_lambda: weight of the final game result z in the value target;
            (1 - z_lambda) goes to the MCTS root Q (bootstrapping).
        legacy: read the v1 format (T1 runs, no flags/king_corner tail).

    __getitem__ returns:
        planes        (11, 11, 11) float32
        legal_mask    (4840,) bool
        policy        (4840,) float32 — normalized visit distribution
        value         () float32 — bootstrapped value target
        policy_valid  () float32 — 1.0 if the policy target came from a full search
        aux_policy    (4840,) float32 — opponent's reply distribution (next sample)
        aux_legal     (4840,) bool — legal mask of the opponent's position
        aux_valid     () float32 — 1.0 if aux_policy is usable
        corner        () int64 — king escape corner class (0-3, 4 = none)
    """

    def __init__(self, path: Path | str, window_size: int = 0, augment: bool = True,
                 z_lambda: float = 0.5, legacy: bool = False) -> None:
        self._path = Path(path)
        self._legacy = legacy
        tail = TAIL_BYTES_V1 if legacy else TAIL_BYTES_V2
        offsets = _build_offset_index(self._path, tail)

        if window_size > 0 and len(offsets) > window_size:
            offsets = offsets[-window_size:]

        self._offsets = offsets
        self._file_size = self._path.stat().st_size
        self._augment = augment
        self._z_lambda = z_lambda
        # File handle opened lazily per worker process
        self._fh = None

    def __len__(self) -> int:
        return len(self._offsets)

    def _get_fh(self):
        """Return an open file handle, creating one if needed (per-worker)."""
        if self._fh is None:
            self._fh = open(self._path, "rb")
        return self._fh

    def __getitem__(self, idx: int):
        fh = self._get_fh()
        planes, legal_mask, policy, value, policy_valid, last_of_game, corner, next_offset, root_q = \
            _read_sample_at(fh, int(self._offsets[idx]), self._z_lambda, self._legacy)

        # Opponent-reply auxiliary target: the next sample of the same game.
        # FLAG_LAST_OF_GAME guards the game boundary; the file-size check
        # guards a truncated final game.
        aux_valid = False
        aux_policy_np = None
        aux_legal_np = None
        if not self._legacy and not last_of_game and next_offset < self._file_size:
            aux_policy_np, aux_legal_np, aux_valid = _read_aux_policy_at(fh, next_offset)
        if aux_policy_np is None:
            aux_policy_np = np.zeros(POLICY_SIZE, dtype=np.float32)
            aux_legal_np = np.zeros(POLICY_SIZE, dtype=np.float32)
        aux_policy = torch.from_numpy(aux_policy_np)
        aux_legal = torch.from_numpy(aux_legal_np).bool()

        if self._augment:
            sym = int(np.random.randint(8))
            if sym > 0:
                planes = torch.from_numpy(_apply_board_sym(planes.numpy(), sym))
                perm = _POLICY_PERMS[sym]
                policy = policy[perm]
                legal_mask = legal_mask[perm]
                aux_policy = aux_policy[perm]
                aux_legal = aux_legal[perm]
                corner = _CORNER_PERMS[sym][corner]

        return (
            planes,
            legal_mask,
            policy,
            value,
            torch.tensor(1.0 if policy_valid else 0.0),
            aux_policy,
            aux_legal,
            torch.tensor(1.0 if aux_valid else 0.0),
            torch.tensor(corner, dtype=torch.long),
            torch.tensor(np.float32(root_q)),
        )

    def __del__(self) -> None:
        if self._fh is not None:
            self._fh.close()
